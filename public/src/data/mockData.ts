function parseHours(hStr: string): number {
  if (!hStr || hStr === '0') return 0;
  if (!hStr.includes(':')) return parseFloat(hStr) || 0;
  const [h, m] = hStr.split(':').map(Number);
  return Math.round(((h || 0) + (m || 0) / 60) * 100) / 100;
}

